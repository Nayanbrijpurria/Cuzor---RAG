package com.cuzor.rag.services

import com.cuzor.rag.csv.CsvReader
import com.cuzor.rag.repository.EmbeddingRepository
import com.cuzor.rag.repository.TicketRepository
import kotlinx.coroutines.*
class TicketImportService {

    suspend fun importCsv(
        filePath: String
    ): ImportResult {

        println("===================================")
        println("Starting Ticket Import")
        println("CSV File : $filePath")
        println("===================================")

        // 1. Read CSV
        val tickets = CsvReader.read(filePath)

        println(
            "Tickets Found : ${tickets.size}"
        )


        var newTickets = 0
        var existingTickets = 0
        var embeddingsAlreadyExist = 0

        // 2. Process every ticket
        var failedTickets = 0

        for (ticket in tickets) {

            try {

                println("-----------------------------------")
                println("Processing Ticket : ${ticket.ticketId}")

                val ticketExists = TicketRepository.exists(ticket.ticketId)
                val embeddingExists = EmbeddingRepository.exists(ticket.ticketId)

                if (ticketExists) {

                    println("Ticket already exists : ${ticket.ticketId}")
                    existingTickets++

                    if (embeddingExists) {
                        println("Embedding already exists : ${ticket.ticketId}")
                        embeddingsAlreadyExist++
                    }

                    continue
                }

                println("New ticket found : ${ticket.ticketId}")

                TicketRepository.save(ticket)

                newTickets++

                println("Ticket saved : ${ticket.ticketId}")

            } catch (e: Exception) {

                failedTickets++

                println("===================================")
                println("TICKET IMPORT FAILED")
                println("Ticket ID : ${ticket.ticketId}")
                println("Error     : ${e.message}")
                println("===================================")

                // Continue with the next ticket.
            }
        }

        println("===================================")
        println("Ticket Import Finished")
        println("===================================")

        println(
            "Total Tickets          : ${tickets.size}"
        )

        println(
            "New Tickets            : $newTickets"
        )

        println(
            "Existing Tickets       : $existingTickets"
        )

        println(
            "Embeddings Already Exist : $embeddingsAlreadyExist"
        )

        println(
            "Embeddings Generated   : 0"
        )

        println(
            "Embeddings will now be generated by the background worker."
        )

        println("===================================")

        return ImportResult(

            totalTickets = tickets.size,

            newTickets = newTickets,

            existingTickets = existingTickets,

            embeddingsGenerated = 0,

            embeddingsSkipped = embeddingsAlreadyExist
        )
    }
}


data class ImportResult(

    val totalTickets: Int,

    val newTickets: Int,

    val existingTickets: Int,

    val embeddingsGenerated: Int,

    val embeddingsSkipped: Int
)